<#
.SYNOPSIS
    Intune-WUO detection script (Intune Remediations). Version __VERSION__. Self-contained: nothing to install.
.DESCRIPTION
    Checks what stops Windows Update and Windows Autopatch from keeping this device up to date, and prints a
    one-line status for the Intune report, for example:
        WUO|v1|NonCompliant|Mode=Script|Build=26100|F=SVC_DISABLED_wuauserv,PAUSE_QUALITY_USER
    It changes nothing on the device. Its only write is the date each offered update was first seen
    (HKLM\SOFTWARE\IntuneWUO\State), which is how "overdue" is measured.

    Exit 0 = healthy (no Warning or Critical finding). Exit 1 = issues found; if the package also has the
    remediation script, Intune runs it next. A failure of this script itself exits 0 so it never triggers a fix.

    Intune settings: run as SYSTEM (logged-on credentials = No), 64-bit PowerShell = Yes,
    signature check = No unless you sign the scripts. Logs: %ProgramData%\Microsoft\IntuneManagementExtension\Logs\IntuneWUO
.NOTES
    Generated by build\Build-RemediationScripts.ps1 from src\IntuneWUO and src\Standalone. Do not edit the
    engine region by hand; edit the source and rebuild. The settings block may be edited.
    Source: https://github.com/bmrepository/Intune-WUOP
#>

#__SETTINGS__

$WUOScriptVersion = '__VERSION__'

#region IntuneWUO engine (generated, do not edit)
New-Module -Name IntuneWUO -ScriptBlock {
Set-StrictMode -Version 2.0
#__ENGINE__
} | Import-Module -Force
#endregion

$ErrorActionPreference = 'Stop'

try {
    $raw = @{ Mode = 'Remediate' }
    foreach ($k in $WUOSettings.Keys) { $raw[$k] = [string]$WUOSettings[$k] }
    $config = ConvertTo-WUOConfig -Raw $raw
    foreach ($w in $config.Warnings) { Write-WUOLog -Level Warning -Component 'Detect' -Message $w }
    try { Register-WUOEventSource } catch { }

    $state = Get-WUOState -IncludeOfferedUpdates:([bool]$config.InstallOverdueUpdates)
    $findings = @(Get-WUOFinding -State $state -Config $config)

    foreach ($key in $state.CollectionErrors.Keys) {
        Write-WUOLog -Level Warning -Component 'Detect' -Message "State collection failed for ${key}: $($state.CollectionErrors[$key])"
    }
    Write-WUOLog -Component 'Detect' -Message "Detection $WUOScriptVersion complete: $($findings.Count) finding(s)." -Data @{
        findings = @($findings | ForEach-Object { @{ id = $_.Id; severity = $_.Severity; autoFix = $_.AutoFix; message = $_.Message } })
        build    = $state.OS.Build
    }
    Write-WUOEvent -Id (Get-WUOEventId -Kind RunComplete) -Message ("Detection {0}; findings: {1}" -f $WUOScriptVersion, (($findings | ForEach-Object Id) -join ', '))
    foreach ($f in $findings | Where-Object { $_.Severity -ne 'Info' }) {
        Write-WUOEvent -Id (Get-WUOEventId -Kind Finding -FindingId $f.Id) -EntryType Warning -Message "$($f.Id): $($f.Message)"
    }

    $ring = if ($state.Autopatch) { $state.Autopatch['Ring'] } else { $null }
    Write-Output (Format-WUOStatus -Config $config -Findings $findings -Build $state.OS.Build -Ring $ring -ModeLabel 'Script')

    if (@($findings | Where-Object { $_.Severity -in 'Warning', 'Critical' }).Count -gt 0) { exit 1 }
    exit 0
}
catch {
    try {
        Write-WUOLog -Level Error -Component 'Detect' -Message $_.Exception.Message
        Write-WUOEvent -Id 9000 -EntryType Error -Message $_.Exception.Message
    } catch { }
    $msg = $_.Exception.Message
    if ($msg.Length -gt 1900) { $msg = $msg.Substring(0, 1900) }
    Write-Output ('WUO|v1|Error|{0}' -f $msg)
    exit 0
}
