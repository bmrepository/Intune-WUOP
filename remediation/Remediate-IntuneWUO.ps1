$script:WUOTaskPath = '\IntuneWUO\'
$script:WUOTaskName = 'IntuneWUO-Fallback'

function New-WUOFallbackTaskDefinition {
    <#
    .SYNOPSIS
        Builds (does not register) the fallback scheduled task parts: daily at 10:00 + up to 6 h random delay,
        at startup + 15 min, catch-up after a missed run, SYSTEM, AC power and network required, 4 h limit,
        one instance at a time.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][string]$InstallDir,
        [ValidateSet('Bypass', 'AllSigned')][string]$ExecutionPolicy = 'Bypass'
    )

    $script = Join-Path $InstallDir 'Invoke-WUOFallback.ps1'
    $ps = Join-Path $env:windir 'System32\WindowsPowerShell\v1.0\powershell.exe'
    $action = New-ScheduledTaskAction -Execute $ps -WorkingDirectory $InstallDir -Argument (
        '-NoProfile -NonInteractive -WindowStyle Hidden -ExecutionPolicy {0} -File "{1}"' -f $ExecutionPolicy, $script)

    $daily = New-ScheduledTaskTrigger -Daily -At '10:00' -RandomDelay (New-TimeSpan -Hours 6)
    $startup = New-ScheduledTaskTrigger -AtStartup
    $startup.Delay = 'PT15M'

    $settings = New-ScheduledTaskSettingsSet -StartWhenAvailable -RunOnlyIfNetworkAvailable `
        -MultipleInstances IgnoreNew -ExecutionTimeLimit (New-TimeSpan -Hours 4)
    $settings.DisallowStartIfOnBatteries = $true
    $settings.StopIfGoingOnBatteries = $true
    $settings.WakeToRun = $false

    $principal = New-ScheduledTaskPrincipal -UserId 'NT AUTHORITY\SYSTEM' -LogonType ServiceAccount -RunLevel Highest

    [pscustomobject]@{
        TaskPath  = $script:WUOTaskPath
        TaskName  = $script:WUOTaskName
        Action    = $action
        Triggers  = @($daily, $startup)
        Settings  = $settings
        Principal = $principal
    }
}

function Register-WUOFallbackTask {
    <# Registers (or replaces) the fallback task. Needs admin. #>
    [CmdletBinding(SupportsShouldProcess)]
    param(
        [Parameter(Mandatory)][string]$InstallDir,
        [ValidateSet('Bypass', 'AllSigned')][string]$ExecutionPolicy = 'Bypass'
    )
    $d = New-WUOFallbackTaskDefinition -InstallDir $InstallDir -ExecutionPolicy $ExecutionPolicy
    if ($PSCmdlet.ShouldProcess("$($d.TaskPath)$($d.TaskName)", 'Register scheduled task')) {
        Register-ScheduledTask -TaskPath $d.TaskPath -TaskName $d.TaskName -Action $d.Action -Trigger $d.Triggers `
            -Settings $d.Settings -Principal $d.Principal -Force | Out-Null
    }
}

function Unregister-WUOFallbackTask {
    [CmdletBinding()]
    param()
    $t = Get-ScheduledTask -TaskPath $script:WUOTaskPath -TaskName $script:WUOTaskName -ErrorAction SilentlyContinue
    if ($t) { Unregister-ScheduledTask -InputObject $t -Confirm:$false }
}

function Get-WUOFallbackTaskStatus {
    <# Returns Present/Enabled for the fallback task. Read-only. #>
    [CmdletBinding()]
    param()
    $t = Get-ScheduledTask -TaskPath $script:WUOTaskPath -TaskName $script:WUOTaskName -ErrorAction SilentlyContinue
    @{ Present = [bool]$t; Enabled = [bool]($t -and $t.State -ne 'Disabled') }
}
} | Import-Module -Force
#endregion

$ErrorActionPreference = 'Stop'
$lock = $null

try {
    $raw = @{ Mode = 'Remediate' }
    foreach ($k in $WUOSettings.Keys) { $raw[$k] = [string]$WUOSettings[$k] }
    $config = ConvertTo-WUOConfig -Raw $raw
    try { Register-WUOEventSource } catch { }

    $lock = Enter-WUOLock
    if (-not $lock) {
        Write-WUOLog -Component 'Remediate' -Message 'Another IntuneWUO run holds the lock; exiting.'
        Write-Output 'WUO|v1|NoAction|Busy'
        exit 0
    }

    $state = Get-WUOState -IncludeOfferedUpdates:([bool]$config.InstallOverdueUpdates)
    $findings = @(Get-WUOFinding -State $state -Config $config)

    $actions = Get-WUODefaultActions
    # The scan just done above is reused, so the install acts on exactly what detection judged overdue.
    $backend = Get-WUODefaultFallbackBackend
    $backend['GetOffered'] = { @($state.OfferedUpdates) }.GetNewClosure()
    $actions['InstallUpdates'] = {
        param($f)
        $run = Invoke-WUOFallbackRun -Config $config -State $state -Backend $backend
        Write-WUOLog -Component 'Remediate' -Message "Update install: $($run.Outcome)" -Data @{
            guardrails = @($run.Guardrails)
            installed  = @($run.Installed)
            failed     = @($run.Failed)
            decisions  = @($run.Candidates | ForEach-Object { @{ title = $_.Update.Title; kb = $_.Update.KB; reason = $_.Reason; ageDays = $_.AgeDays } })
        }
        switch ($run.Outcome) {
            'Blocked' {
                Write-WUOEvent -Id (Get-WUOEventId -Kind FallbackSkipped) -Message ('Update install blocked: ' + (@($run.Guardrails) -join ', '))
                return 'SKIP: blocked by ' + (@($run.Guardrails) -join ',')
            }
            'NothingEligible' { return 'SKIP: nothing eligible' }
            'Skipped' { return 'SKIP: installs not enabled' }
            'PartiallyFailed' {
                Write-WUOEvent -Id (Get-WUOEventId -Kind FallbackFailed) -EntryType Error -Message ('Update install failed for: ' + (@($run.Failed) -join ', '))
                throw ('Installed {0}, failed {1}' -f @($run.Installed).Count, (@($run.Failed) -join ','))
            }
            default {
                Write-WUOEvent -Id (Get-WUOEventId -Kind FallbackInstalled) -Message ('Installed: ' + (@($run.Installed) -join ', '))
                return "Installed $(@($run.Installed).Count) update(s); restart left to the native deadline"
            }
        }
    }.GetNewClosure()

    $results = @(Invoke-WUORemediation -Findings $findings -Config $config -Actions $actions)

    foreach ($r in $results) {
        $level = if ($r.Outcome -eq 'Failed') { 'Error' } elseif ($r.Outcome -eq 'Suppressed') { 'Warning' } else { 'Info' }
        Write-WUOLog -Level $level -Component 'Remediate' -Message "$($r.Id): $($r.Outcome) $($r.Reason) $($r.Detail)".Trim() `
            -Data @{ id = $r.Id; outcome = $r.Outcome; reason = $r.Reason }
        if ($r.Outcome -eq 'Fixed') {
            Write-WUOEvent -Id (Get-WUOEventId -Kind Fix -FindingId $r.Id) -Message "$($r.Id) fixed: $($r.Detail)"
        }
        elseif ($r.Outcome -eq 'Failed') {
            Write-WUOEvent -Id (Get-WUOEventId -Kind FixFailed -FindingId $r.Id) -EntryType Error -Message "$($r.Id) fix failed: $($r.Detail)"
        }
    }

    $fixed = @($results | Where-Object Outcome -eq 'Fixed' | ForEach-Object Id)
    $failed = @($results | Where-Object Outcome -eq 'Failed' | ForEach-Object Id)
    $suppressed = @($results | Where-Object Outcome -eq 'Suppressed' | ForEach-Object Id)
    $reportOnly = @($findings | Where-Object { $_.AutoFix -eq 'None' -and $_.Severity -ne 'Info' } | ForEach-Object Id)
    $out = 'WUO|v1|Remediated|Fixed={0}|Failed={1}|Suppressed={2}|AdminAction={3}' -f `
        ($fixed -join ','), ($failed -join ','), ($suppressed -join ','), ($reportOnly -join ',')
    if ($out.Length -gt 2048) { $out = $out.Substring(0, 2048) }
    Write-Output $out

    if ($failed.Count -gt 0) { exit 1 }
    exit 0
}
catch {
    try {
        Write-WUOLog -Level Error -Component 'Remediate' -Message $_.Exception.Message
        Write-WUOEvent -Id 9000 -EntryType Error -Message $_.Exception.Message
    } catch { }
    $msg = $_.Exception.Message
    if ($msg.Length -gt 1900) { $msg = $msg.Substring(0, 1900) }
    Write-Output ('WUO|v1|Error|{0}' -f $msg)
    exit 1
}
finally {
    if ($lock) { Exit-WUOLock -Mutex $lock }
}
