<#
.SYNOPSIS
    Intune-WUO remediation script (Intune Remediations). Version 1.0.0. Self-contained: nothing to install.
.DESCRIPTION
    Intune runs this only after the detection script exits 1. It checks the device again (so it acts on current
    facts) and applies the fixes the settings block allows:
      - re-enables disabled update services
      - clears update pauses set by a user (never a pause set by policy)
      - starts an Intune sync when the last one is stale; cleans up when disk space is low
      - installs approved quality updates that are overdue (never drivers or feature updates)
      - resets the update stack only if FixResetStack = 1
    It never restarts the device, never changes update policy, Autopatch, VBS or CHPE, and never removes
    Group Policy or ConfigMgr settings: those are reported for the admin. A fix that keeps being undone is
    suppressed after FixMaxRepeats times in 7 days.

    Exit 0 = everything attempted succeeded or was legitimately skipped. Exit 1 = at least one fix failed.
    Intune then runs the detection script again and reports the result.
.NOTES
    Generated by build\Build-RemediationScripts.ps1 from src\IntuneWUO and src\Standalone. Do not edit the
    engine region by hand; edit the source and rebuild. The settings block may be edited.
    Source: https://github.com/bmrepository/Intune-WUOP
#>

